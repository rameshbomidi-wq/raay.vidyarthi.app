#!/usr/bin/env python3
"""books/AP_CSE_TextBooks_2025-26_Telugu_English.html (యూజర్ ఇచ్చిన ఫైల్ – మార్చకూడదు) లోని BOOKS
→ index.html లో APBOOKS25 markers మధ్య తరగతి వారీ data: [తెలుగు పేరు, మూల పేరు, URL, sem(0/1/2), రకం].
వాడకం: python3 tools/book_links/build_links_2025.py"""
import json, re, sys
SRC = 'books/AP_CSE_TextBooks_2025-26_Telugu_English.html'
TY = {'Text Book': 'పాఠ్యపుస్తకం', 'Work Book': 'వర్క్‌బుక్', 'Hand Book': 'టీచర్ హ్యాండ్‌బుక్'}
SUB = [('TELUGU, ENGLISH, MATHS', 'భాషలు + గణితం'), ('TELUGU, HINDI, ENGLISH', 'భాషలు'), ('TELUGU, ENGLISH', 'భాషలు'),
       ('MATHS, EVS', 'గణితం + పరిసరాల విజ్ఞానం'), ('ORIENTAL COMPOSITE SANSKRIT', 'సంస్కృతం (ఓరియంటల్)'),
       ('COMPOSIT COURSE SANSKRIT', 'సంస్కృతం (కాంపోజిట్)'), ('VALUE EDUCATION', 'నైతిక విలువలు'),
       ('GENERAL SCIENCE', 'సైన్స్'), ('SOCIAL', 'సాంఘికం'), ('BIOLOGICAL', 'జీవశాస్త్రం'), ('PHYSIC', 'భౌతిక శాస్త్రం'),
       ('ECONOMICS', 'అర్థశాస్త్రం'), ('POLITICAL', 'రాజకీయశాస్త్రం'), ('GEOGRAPHY', 'భూగోళం'), ('HISTORY', 'చరిత్ర'),
       ('MATHS', 'గణితం'), ('EVS', 'పరిసరాల విజ్ఞానం'), ('ENGLISH', 'English'), ('HINDI', 'హిందీ'), ('TELUGU', 'తెలుగు')]
def subj(b):
    s = b['subject']
    if 'SECOND LANGUAGE' in b['name']: return 'తెలుగు ద్వితీయ భాష'
    if s.startswith('GENERAL SCIENCE') and 'PHYSICAL' in b['name']: return 'భౌతిక శాస్త్రం'
    if s.startswith('GENERAL SCIENCE') and 'BIOLOG' in b['name']: return 'జీవశాస్త్రం'
    for k, v in SUB:
        if s.startswith(k): return v
    return s.title()
html = open(SRC, encoding='utf-8').read()
books = json.loads(re.search(r'const BOOKS=(\[.*?\]);\n', html, re.S).group(1))
cat = {}
for b in books:
    assert b['url'].startswith('https://cse.ap.gov.in/loadsupdocumentuploadbyid?req_doc_id=2025-2026'), b
    sem = int(b['semester'])
    t = subj(b) + ' — ' + TY.get(b['type'], b['type']) + (f' — SEM{sem}' if sem else '')
    cat.setdefault(str(b['class']), []).append([t, b['name'] + ' (' + b['type'] + ')', b['url'], sem, b['type'][0]])
data = json.dumps(cat, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/')
idx = open('index.html', encoding='utf-8').read()
a, z = '/* APBOOKS25-START: generated by tools/book_links/build_links_2025.py */', '/* APBOOKS25-END */'
blk = f'{a}\nconst APBOOKS25={data};\n{z}'
if a in idx:
    idx = re.sub(re.escape(a) + r'.*?' + re.escape(z), lambda m: blk, idx, flags=re.S)
else:
    m = '/* APBOOKS-DATA-END */'
    assert idx.count(m) == 1
    idx = idx.replace(m, m + '\n' + blk)
open('index.html', 'w', encoding='utf-8').write(idx)
print(len(books), 'పుస్తకాలు;', {k: len(v) for k, v in cat.items()})
