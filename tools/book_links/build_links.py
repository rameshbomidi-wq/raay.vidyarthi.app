#!/usr/bin/env python3
"""Build the AP 2026–27 textbook-link catalog from the supplied Markdown source.

The source is a link index only.  This script deliberately does not download or
interpret PDFs; it preserves every source title and URL and emits a compact JS
constant for the application to consume.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Iterable
from urllib.parse import parse_qsl, urlsplit

START_MARKER = "/* APBOOKS-DATA-START: generated by tools/book_links/build_links.py */"
END_MARKER = "/* APBOOKS-DATA-END */"
DEFAULT_OUTPUT = Path("/home/ubuntu/book-links-app/ap_catalog.js")
SOURCE_RELATIVE = Path("books/AP_Textbook_Links_2026-27_Telugu-English.md")
EXPECTED_COUNTS = {1: 4, 2: 4, 3: 7, 4: 6, 5: 6, 6: 6, 7: 6, 8: 6, 9: 7, 10: 14}
BASE_URL = "https://cse.ap.gov.in/loadsupdocumentuploadbyid"

SECTION_RE = re.compile(r"^\s*##\s+(\d+)వ\s+తరగతి(?:\s|—|-|$)")
ENTRY_RE = re.compile(r"^\s*\d+\.\s+\[([^\]]+)\]\(([^\s)]+)\)\s*$")
DOC_ID_RE = re.compile(r"^2026-2027[WT](\d{2})(?:[^\s]*)$")
SEMESTER_RE = re.compile(r"SEM[12]", re.IGNORECASE)


class LinkBuildError(ValueError):
    """Raised when the source cannot be safely converted into the catalog."""


def _error(message: str) -> LinkBuildError:
    return LinkBuildError(message)


def parse_source(markdown: str) -> dict[int, list[dict[str, object]]]:
    """Parse numbered Markdown link entries grouped by their grade heading."""
    grades: dict[int, list[dict[str, object]]] = {}
    current_grade: int | None = None
    seen_entry_lines: set[int] = set()

    for line_number, line in enumerate(markdown.splitlines(), 1):
        section = SECTION_RE.match(line)
        if section:
            grade = int(section.group(1))
            if grade in grades:
                raise _error(f"duplicate grade section {grade} at line {line_number}")
            grades[grade] = []
            current_grade = grade
            continue

        if re.match(r"^\s*\d+\.\s+", line):
            if current_grade is None:
                raise _error(f"numbered link before a grade section at line {line_number}")
            entry = ENTRY_RE.match(line)
            if not entry:
                raise _error(f"malformed numbered Markdown link at line {line_number}")
            title, url = entry.groups()
            grades[current_grade].append(
                {"grade": current_grade, "title": title, "url": url, "line": line_number}
            )
            seen_entry_lines.add(line_number)

    if not grades:
        raise _error("no grade sections found")
    unexpected = sorted(set(grades) - set(EXPECTED_COUNTS))
    missing = sorted(set(EXPECTED_COUNTS) - set(grades))
    if unexpected:
        raise _error(f"unexpected grade section(s): {unexpected}")
    if missing:
        raise _error(f"missing grade section(s): {missing}")
    for grade, expected in EXPECTED_COUNTS.items():
        actual = len(grades[grade])
        if actual != expected:
            raise _error(f"grade {grade} has {actual} links; expected {expected}")
    return grades


def _validate_url(grade: int, url: str, line: int) -> str:
    parsed = urlsplit(url)
    if url != url.strip() or parsed.scheme != "https" or parsed.netloc != "cse.ap.gov.in":
        raise _error(f"line {line}: URL must use https://cse.ap.gov.in")
    if parsed.path != "/loadsupdocumentuploadbyid":
        raise _error(f"line {line}: unexpected CSE AP document path")
    query = parse_qsl(parsed.query, keep_blank_values=True)
    if len(query) != 1 or query[0][0] != "req_doc_id" or not query[0][1]:
        raise _error(f"line {line}: URL must contain exactly one req_doc_id query value")
    doc_id = query[0][1]
    match = DOC_ID_RE.fullmatch(doc_id)
    if not match:
        raise _error(f"line {line}: invalid document ID {doc_id!r}")
    if int(match.group(1)) != grade:
        raise _error(f"line {line}: document ID grade does not match section {grade}")
    return doc_id


def validate_source(grades: dict[int, list[dict[str, object]]]) -> None:
    """Validate URL shape, document IDs, source order, and uniqueness."""
    seen_urls: dict[str, int] = {}
    for grade in EXPECTED_COUNTS:
        for entry in grades[grade]:
            url = str(entry["url"])
            line = int(entry["line"])
            _validate_url(grade, url, line)
            if url in seen_urls:
                raise _error(
                    f"duplicate URL at line {line}; first appeared at line {seen_urls[url]}"
                )
            seen_urls[url] = line
    if len(seen_urls) != sum(EXPECTED_COUNTS.values()):
        raise _error(f"expected 66 unique URLs; found {len(seen_urls)}")


def _subject(original_title: str) -> str:
    """Infer only the conservative Telugu display subject from the raw title."""
    upper = original_title.upper()
    normalized = re.sub(r"[\s_]+", " ", upper).strip()
    if "SECOND LANGUAGE TELUGU" in normalized:
        return "తెలుగు ద్వితీయ భాష"
    if "SOCIAL-POLITICALSCIENCE" in normalized or "SOCIAL - POLITICALSCIENCE" in normalized:
        return "రాజకీయశాస్త్రం"
    if "SOCIAL-HISTORY" in normalized or "SOCIAL - HISTORY" in normalized:
        return "చరిత్ర"
    if "SOCIAL-GEOGRAPHY" in normalized or "SOCIAL - GEOGRAPHY" in normalized:
        return "భూగోళం"
    if "SOCIAL-ECONOMICS" in normalized or "SOCIAL - ECONOMICS" in normalized:
        return "అర్థశాస్త్రం"
    if "MATHEMATICS" in normalized:
        return "గణితం"
    if "BIOLOGICAL SCIENCE" in normalized:
        return "జీవశాస్త్రం"
    if "PHYSICAL SCIENCE" in normalized:
        return "భౌతిక శాస్త్రం"
    if "GENERAL SCIENCE" in normalized or re.search(r"\bSCIENCE\b", normalized):
        return "సైన్స్"
    if "HINDI" in normalized:
        return "హిందీ"
    if "TELUGU" in normalized:
        return "తెలుగు"
    if "ENGLISH" in normalized:
        return "English"
    if re.search(r"NON\s*-?\s*LANGUAGES", normalized):
        return "భాషేతర విషయాలు"
    if re.search(r"\bLANGUAGES\b", normalized):
        return "భాషలు"
    # The class 1/2 bundle titles intentionally have no inferred language.
    return ""


def _book_type(original_title: str) -> str:
    upper = original_title.upper()
    if "WORK BOOK" in upper or re.search(r"\bWB\b", upper):
        return "వర్క్‌బుక్"
    if re.search(r"\bSR\b", upper):
        return "ఉపవాచకం"
    return "పాఠ్యపుస్తకం"


def friendly_title(original_title: str) -> str:
    """Return a conservative Telugu-friendly label derived only from the title."""
    parts = [_subject(original_title), _book_type(original_title)]
    semester = SEMESTER_RE.search(original_title)
    if semester:
        parts.append(semester.group(0).upper())
    return " — ".join(part for part in parts if part)


def source_warning(grade: int, original_title: str, doc_id: str) -> str:
    """Return warnings for source ambiguities explicitly identified by the user."""
    upper = original_title.upper()
    if grade == 3 and doc_id.startswith("2026-2027W03") and re.search(r"CLASS\s*2(?!\d)", upper):
        return "మూల పేరులో 2వ తరగతి ఉంది; ఇది 3వ తరగతి జాబితాలో ఉంది. PDF చూసి ధృవీకరించండి."
    if grade in (9, 10) and "WORK BOOK" in upper and "(TEXT BOOK)" in upper:
        return "మూల పేరులో Work Book ఉన్నా మూల లేబుల్ Text Bookగా ఉంది; PDF చూసి ధృవీకరించండి."
    return ""


def build_catalog(markdown: str) -> dict[str, list[list[str]]]:
    """Parse and validate Markdown, returning the JSON-ready graded row object."""
    grades = parse_source(markdown)
    validate_source(grades)
    catalog: dict[str, list[list[str]]] = {}
    for grade in EXPECTED_COUNTS:
        rows: list[list[str]] = []
        for entry in grades[grade]:
            title = str(entry["title"])
            url = str(entry["url"])
            doc_id = _validate_url(grade, url, int(entry["line"]))
            rows.append([friendly_title(title), title, url, source_warning(grade, title, doc_id)])
        catalog[str(grade)] = rows
    return catalog


def render_block(catalog: dict[str, list[list[str]]]) -> str:
    """Render the exact marker-delimited compact JavaScript block."""
    payload = json.dumps(catalog, ensure_ascii=False, separators=(",", ":"))
    # Keep the block safe if it is later embedded inside an HTML <script> while
    # retaining identical values when JavaScript/JSON decodes it.
    payload = payload.replace("</", "<\\/").replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
    return f"{START_MARKER}\nconst APBOOKS={payload};\n{END_MARKER}"


def update_index(index_path: Path, block: str) -> None:
    """Replace only the existing APBOOKS marker block in an index file."""
    text = index_path.read_text(encoding="utf-8")
    start = text.find(START_MARKER)
    end = text.find(END_MARKER)
    if start < 0 or end < 0 or end < start:
        raise _error(f"APBOOKS markers absent or out of order in {index_path}")
    if text.find(START_MARKER, start + len(START_MARKER)) >= 0 or text.find(END_MARKER, end + len(END_MARKER)) >= 0:
        raise _error(f"APBOOKS markers must occur exactly once in {index_path}")
    end += len(END_MARKER)
    index_path.write_text(text[:start] + block + text[end:], encoding="utf-8")


def _default_repo() -> Path:
    return Path(__file__).resolve().parents[2]


def main(argv: Iterable[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=_default_repo(), help="repository root")
    parser.add_argument("--source", type=Path, help="source Markdown path")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT, help="generated JS path")
    parser.add_argument(
        "--update-index",
        action="store_true",
        help="also replace the marker-delimited APBOOKS block in <repo>/index.html",
    )
    args = parser.parse_args(list(argv) if argv is not None else None)
    repo = args.repo.resolve()
    source = (args.source or (repo / SOURCE_RELATIVE)).resolve()
    output = args.output.resolve()
    try:
        catalog = build_catalog(source.read_text(encoding="utf-8"))
        block = render_block(catalog)
        index = (repo / "index.html").resolve()
        # Validate marker availability before writing the generated artifact so a
        # requested index update fails without a partial update.
        if args.update_index:
            index_text = index.read_text(encoding="utf-8")
            start = index_text.find(START_MARKER)
            end = index_text.find(END_MARKER)
            if start < 0 or end < 0 or end < start:
                raise _error(f"APBOOKS markers absent or out of order in {index}")
            if index_text.find(START_MARKER, start + len(START_MARKER)) >= 0 or index_text.find(END_MARKER, end + len(END_MARKER)) >= 0:
                raise _error(f"APBOOKS markers must occur exactly once in {index}")
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(block + "\n", encoding="utf-8")
        if args.update_index:
            update_index(index, block)
    except (OSError, UnicodeError, LinkBuildError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    counts = ", ".join(f"{grade}:{len(catalog[str(grade)])}" for grade in EXPECTED_COUNTS)
    print(f"built 66 textbook links ({counts}) -> {output}")
    if args.update_index:
        print(f"updated APBOOKS marker block only -> {repo / 'index.html'}")
    print("caveat: source URLs/titles are preserved; PDF contents, reachability, medium, and edition remain unverified.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
