def rt(a, b, sides=('', '', ''), names=('A', 'B', 'C'), th='θ', th2=None, w=260, cap=None, pad=1.4):
    """A(0,0) వద్ద కోణం, B(a,0) వద్ద లంబకోణం, C(a,b). sides = (AB ఆసన్న, BC ఎదుటి, AC కర్ణం)"""
    t = math.degrees(math.atan2(b, a)); r = min(a, b) * 0.35 + 0.3
    e = [PG([[0, 0], [a, 0], [a, b]], FILL), R(a, 0, 180, 90, min(a, b) * 0.12 + 0.1),
         A(0, 0, r, 0, t, th) if th else None,
         A(a, b, r * 0.8, 180 + t, 270, th2) if th2 else None,
         P(0, 0, names[0], 'sw'), P(a, 0, names[1], 'se'), P(a, b, names[2], 'ne'),
         M(0, 0, a, 0, sides[0], 1) if sides[0] else None, M(a, 0, a, b, sides[1], 1) if sides[1] else None,
         M(0, 0, a, b, sides[2], -1) if sides[2] else None]
    return F([-pad, a + pad * 1.6 + (len(sides[1]) > 4) * a * 0.18, -pad * 0.9, b + pad * 0.6], *e, w=w, cap=cap)

def tower(dist, h, angle_lab, base_lab='', h_lab='h', sc=1.0, w=260, cap=None, names=('A', 'B', 'C')):
    """టవర్ AB (B అడుగు, A పైకొన) – నేలపై C నుండి ఊర్ధ్వ కోణం"""
    d, hh = dist * sc, h * sc; t = math.degrees(math.atan2(hh, d))
    return F([-d * 0.25 - 0.6 - (d * 0.55 if len(h_lab) > 3 else 0), d * 1.15 + 0.4, -d * 0.18 - 0.4, hh * 1.12 + 0.3],
             S(-d * 0.15, 0, d * 1.1, 0), S(0, 0, 0, hh, 'b'), S(d, 0, 0, hh, 'a2'), R(0, 0, 0, 90, d * 0.06 + 0.05),
             A(d, 0, d * 0.22, 180 - t, 180, angle_lab), P(0, hh, names[0], 'nw'), P(0, 0, names[1], 'sw'), P(d, 0, names[2], 'se'),
             M(0, 0, d, 0, base_lab, 1) if base_lab else None, M(0, 0, 0, hh, h_lab, -1) if h_lab else None, w=w, cap=cap)

