SM = '(रेखांकित शब्द का समास विकल्पों में से पहचान कर लिखिए।)'
SV = '(रेखांकित शब्द का संधि विच्छेद विकल्पों में से पहचान कर लिखिए।)'
PD, GD = 'पद्यांश', 'गद्यांश'
AB = 'अ आ इ ई'.split()
class HB(Bank):
    def rc(self, L, passage, qs, ans, kind=PD, lid=None):
        """5 అంకాల పఠనం (4 మార్కుల విభాగంలో): qs = [(ప్రశ్న, [A,B,C,D] | None)], ans = [జవాబు,...]"""
        t = f'निम्नलिखित {kind} पढ़कर दिए गए प्रश्नों के उत्तर निर्देश के अनुसार लिखिए। (5 अंक)\n{passage}\nप्रश्न :'
        for i, (qq, op) in enumerate(qs):
            t += f'\n{AB[i]}) {qq} ({2 if i == 0 else 1} अंक)'
            if op: t += '\n   ' + '   '.join(f'{"ABCD"[j]}) {o}' for j, o in enumerate(op))
        return self.q(L, 4, t, '\n'.join(f'{AB[i]}) {a}' for i, a in enumerate(ans)), lid=lid)
    def w(self, L, sent, instr, opts, k, ex='', lid=None):
        """1 మార్కు – వాక్యం + సూచన + 3 ఎంపికలు (k = సరైనది)"""
        return self.mcq(L, f'{sent} {instr}', opts, k, ex, lid=lid)
